#!/usr/bin/env bash
# Compiles src/data + src/player (pure Java parts) with test/ and runs every test class. Run in Git Bash (Windows) or bash (Linux / CI).
set -uo pipefail
cd "$(dirname "$0")/.."
[ -f local.env ] && { set -a; . ./local.env; set +a; }
case "${OSTYPE:-}" in
  msys*|cygwin*|win32*) AJ=$(cygpath -w "${ANDROID_SDK:-$(cygpath -u "${LOCALAPPDATA:-$HOME/AppData/Local}")/Android/Sdk}/platforms/android-36/android.jar") ;;
  *) AJ="${ANDROID_SDK:-${ANDROID_HOME:-$HOME/Android/Sdk}}/platforms/android-36/android.jar" ;; # Linux / CI
esac
OUT=build-test
rm -rf $OUT && mkdir -p $OUT/cfg/lk/manus/iptv
# Config is generated by build.sh; tests get a stub with the most restrictive (play) values
printf 'package lk.manus.iptv;\npublic final class Config { public static final boolean DEBUG = false, PLAY = %s, IPTVORG = %s; public static final String FEED_URL = ""; public static final String TMDB_KEY = ""; }\n' "${TEST_PLAY:-true}" "${TEST_IPTVORG:-false}" > $OUT/cfg/lk/manus/iptv/Config.java
javac -encoding UTF-8 -nowarn -d $OUT -cp "$AJ" $(find src/lk/manus/iptv/data src/lk/manus/iptv/player src/lk/manus/iptv/meta -name '*.java' | grep -v -E 'Media3Engine|MediaPlayerEngine|MiniPreview') src/lk/manus/iptv/ui/Ui.java $OUT/cfg/lk/manus/iptv/Config.java test/*.java 2> $OUT/javac.log || { cat $OUT/javac.log; rm -rf $OUT; exit 1; }
grep -v -E '^Note|warning' $OUT/javac.log || true
rc=0
case "$OSTYPE" in msys*|cygwin*|win32*) SEP=';';; *) SEP=':';; esac
for t in AudioTest DataLayerTest DbMigrationTest FavGuardTest GroupingTest HlsTest M3uParserTest NormalizerTest SearchTest SubTrTest WebVttTest TitleCleanerTest MatcherTest RemindersTest AddServerTest BackupTest XtreamTest LibraryTest FilmResumeTest ContinueWatchingTest AddXtreamTest SeriesSourceTest SeriesLogicTest CatchupTest FilmOrderTest SeriesClassifierTest ZapLogicTest FailPlanTest ShowGroupsTest SubFitTest LoadTextTest ListToolsTest SearchFilterTest MiniPolicyTest; do
  echo "== $t"
  java -cp "$OUT$SEP$AJ" "$t" test/sample.m3u 2>&1 | tail -${TAILN:-3}
  [ "${PIPESTATUS[0]}" -eq 0 ] || rc=1
done
rm -rf $OUT
exit $rc
